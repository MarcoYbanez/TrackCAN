#!/usr/bin/env python3
"""Generate the dash bar geometry (C tables) and golden checksums from the saved layout.

Input : UI/DigitalDash/dash_bg_layout.json   (made by scripts/extract_dash_layout.py)
        UI/DigitalDash/assets/Main_Tach/MainTachometer00060.png and Top_Tach/TopTach00001.png
Output: DigitalDash_Node/shared/dash_geometry.c / .h   (committed; the firmware draws the bars from these)
        DigitalDash_Node/tests/dash_golden.h           (checksums of the fully lit source frames)

The firmware draws every lit segment pixel for pixel from the tables. The golden checksums let a host test prove
that the C renderer reproduces the original fully lit frames exactly.

Needs Pillow.  Run:  python3 -I scripts/gen_dash_geometry.py
"""
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
LAYOUT = ROOT / "UI/DigitalDash/dash_bg_layout.json"
OUT_C = ROOT / "DigitalDash_Node/shared/dash_geometry.c"
OUT_H = ROOT / "DigitalDash_Node/shared/dash_geometry.h"
OUT_GOLDEN = ROOT / "DigitalDash_Node/tests/dash_golden.h"
FRAMES = {
    "main": ROOT / "UI/DigitalDash/assets/Main_Tach/MainTachometer00060.png",
    "top": ROOT / "UI/DigitalDash/assets/Top_Tach/TopTach00001.png",
}


def argb(hexc):
    return 0xFF000000 | int(hexc[1:], 16)


def fnv1a(data):
    h = 0x811C9DC5
    for b in data:
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def bar_tables(name, segs, frame_size):
    """Flatten the segments into column and baseline arrays, clipped to the source frame. Returns
    (rows, cols, base, bbox)."""
    rows, cols, base = [], [], []
    x_min = min(s["x"] + s["lit_x0"] for s in segs)
    y_min = min(s["y"] for s in segs)
    width, height = frame_size
    starts = [s["x"] + s["lit_x0"] - x_min for s in segs]
    for i, s in enumerate(segs):
        rx = starts[i]
        # Nothing beyond the frame's right edge, and nothing under the NEXT segment: the stored glow column of a
        # segment overlaps the next one's first column. Fully lit the next segment paints over it, but if it is
        # turned off again it would erase its neighbour's pixels, so each segment is clipped to end where the next
        # begins. The fully lit picture is unchanged (the test compares it with the original frame).
        limit = (starts[i + 1] if i + 1 < len(segs) else width) - rx
        ncols = min(len(s["lit_columns"]), limit)
        nbase = min(len(s["lit_base_row"]), limit)
        rows.append((rx, s["y"] - y_min, s["h"], ncols, len(cols), len(base), nbase))
        cols.extend(argb(c) for c in s["lit_columns"][:ncols])
        base.extend(argb(c) for c in s["lit_base_row"][:nbase])
        if s["h"] + 1 > height:
            sys.exit("%s segment taller than the frame" % name)
    return rows, cols, base, (x_min, y_min, width, height)


def golden(path, bbox, name):
    """FNV-1a of the fully lit frame composited on black, as RGB bytes, row by row."""
    im = Image.open(path).convert("RGBA")
    flat = Image.alpha_composite(Image.new("RGBA", im.size, (0, 0, 0, 255)), im).convert("RGB")
    if flat.size != (bbox[2], bbox[3]):
        sys.exit("%s frame is %s but the bar region is %dx%d" % (name, flat.size, bbox[2], bbox[3]))
    return fnv1a(flat.tobytes()), flat.size


def emit_array(f, ctype, name, values, per_line=8, fmt="0x%08X"):
    f.write("const %s %s[%d] = {\n" % (ctype, name, max(1, len(values))))
    for i in range(0, len(values), per_line):
        f.write("    " + ", ".join(fmt % v for v in values[i:i + per_line]) + ",\n")
    f.write("};\n\n")


def main():
    d = json.loads(LAYOUT.read_text())
    bars = {"main": d["main_bar_off_segments"], "top": d["top_bar_off_segments"]}
    fill = d["boost_fill"]
    track = d["boost_track"][0]

    tables = {}
    for name, segs in bars.items():
        if any(not s["lit_columns"] for s in segs):
            sys.exit("%s has a segment without lit_columns; run extract_dash_layout.py first" % name)
        tables[name] = bar_tables(name, segs, Image.open(FRAMES[name]).size)

    with OUT_H.open("w") as h:
        h.write("""/*******************************************************
 * @file dash_geometry.h
 * @brief GENERATED by scripts/gen_dash_geometry.py from UI/DigitalDash/dash_bg_layout.json. Do not edit.
 *
 * Exact pixels of every lit RPM bar segment (60 main, 16 shift lights) and the boost fill rectangle. Coordinates
 * are screen pixels (480 x 272). A bar is drawn into a transparent ARGB8888 buffer that covers its region.
 *******************************************************/
#ifndef DASH_GEOMETRY_H
#define DASH_GEOMETRY_H

#include <stdint.h>

typedef struct {
    uint16_t x;       /* left edge of the first lit column, relative to the bar region */
    uint16_t y;       /* top row, relative to the bar region */
    uint8_t h;        /* rows of the lit segment; the dim baseline is one more row */
    uint8_t ncols;    /* lit columns */
    uint16_t col_off; /* first colour in the bar's column table (ncols entries, opaque ARGB8888) */
    uint16_t base_off; /* first colour in the bar's baseline table */
    uint8_t nbase;     /* baseline entries */
} dash_seg_t;

typedef struct {
    const dash_seg_t *segs;
    uint8_t count;
    const uint32_t *cols;
    const uint32_t *base;
    uint16_t screen_x; /* where the region sits on the 480 x 272 screen */
    uint16_t screen_y;
    uint16_t width;
    uint16_t height;
} dash_bar_t;

""")
        for name, (rows, cols, base, bbox) in tables.items():
            n = name.upper()
            h.write("#define DASH_%s_SEGMENTS %du\n" % (n, len(rows)))
        h.write("\n")
        h.write("#define DASH_BOOST_FILL_X %du\n#define DASH_BOOST_FILL_Y %du\n#define DASH_BOOST_FILL_W_PX %du\n"
                "#define DASH_BOOST_FILL_H_PX %du\n#define DASH_BOOST_FILL_ARGB 0x%08XU\n\n"
                % (fill["x"], fill["y"], fill["w"], fill["h"], argb(fill["colours_in_source_image"][0])))
        h.write("#define DASH_BOOST_TRACK_X %du\n#define DASH_BOOST_TRACK_Y %du\n\n" % (track["x"], track["y"]))
        h.write("extern const dash_bar_t dash_main_bar;\nextern const dash_bar_t dash_top_bar;\n\n#endif /* DASH_GEOMETRY_H */\n")

    with OUT_C.open("w") as c:
        c.write('/* GENERATED by scripts/gen_dash_geometry.py from UI/DigitalDash/dash_bg_layout.json. Do not edit. */\n'
                '#include "dash_geometry.h"\n\n')
        for name, (rows, cols, base, bbox) in tables.items():
            c.write("static const dash_seg_t %s_segs[%d] = {\n" % (name, len(rows)))
            for r in rows:
                c.write("    {%d, %d, %d, %d, %d, %d, %d},\n" % r)
            c.write("};\n\n")
            c.write("static ")
            emit_array(c, "uint32_t", "%s_cols" % name, cols)
            c.write("static ")
            emit_array(c, "uint32_t", "%s_base" % name, base)
            c.write("const dash_bar_t dash_%s_bar = {%s_segs, %d, %s_cols, %s_base, %d, %d, %d, %d};\n\n"
                    % (name, name, len(rows), name, name, bbox[0], bbox[1], bbox[2], bbox[3]))

    with OUT_GOLDEN.open("w") as g:
        g.write("/* GENERATED by scripts/gen_dash_geometry.py. FNV-1a of the fully lit source frames, composited on\n"
                " * black, as RGB bytes row by row. Do not edit. */\n#ifndef DASH_GOLDEN_H\n#define DASH_GOLDEN_H\n\n")
        for name in ("main", "top"):
            hv, size = golden(FRAMES[name], tables[name][3], name)
            g.write("#define DASH_GOLDEN_%s_HASH 0x%08XU\n#define DASH_GOLDEN_%s_W %du\n#define DASH_GOLDEN_%s_H %du\n"
                    % (name.upper(), hv, name.upper(), size[0], name.upper(), size[1]))
        g.write("\n#endif /* DASH_GOLDEN_H */\n")

    for name, (rows, cols, base, bbox) in tables.items():
        print("%-4s %2d segments, region x=%d y=%d %dx%d, %d column colours, %d baseline colours"
              % (name, len(rows), bbox[0], bbox[1], bbox[2], bbox[3], len(cols), len(base)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
